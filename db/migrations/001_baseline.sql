-- ============================================================
-- Media table
-- ============================================================
create table public.media (
  id          bigint generated by default as identity not null,
  created_at  timestamp with time zone not null default now(),
  name        character varying null,
  alt         character varying null,
  storage_path character varying null,        -- path inside the Supabase Storage bucket
  mime_type   character varying null,
  size        bigint null,                    -- file size in bytes
  constraint media_pkey primary key (id)
) tablespace pg_default;

-- ============================================================
-- Indexes
-- ============================================================
create index if not exists media_created_at_idx on public.media (created_at desc);

-- ============================================================
-- Row Level Security
-- ============================================================
alter table public.media enable row level security;

-- Anyone (including anonymous visitors) can read media records
-- so they can be displayed on the public-facing site.
create policy "media_select_public"
  on public.media
  for select
  using (true);

-- Only authenticated users (admins / editors) can insert media.
create policy "media_insert_authenticated"
  on public.media
  for insert
  with check (auth.role() = 'authenticated');

-- Only authenticated users can update media records.
create policy "media_update_authenticated"
  on public.media
  for update
  using  (auth.role() = 'authenticated')
  with check (auth.role() = 'authenticated');

-- Only authenticated users can delete media records.
create policy "media_delete_authenticated"
  on public.media
  for delete
  using (auth.role() = 'authenticated');
